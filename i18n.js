const SUPPORT_LANGS = [
  ["en", "English"], ["de", "Deutsch"], ["fr", "Français"], ["it", "Italiano"],
  ["es", "Español"], ["pt-BR", "Português (Brasil)"], ["nl", "Nederlands"],
  ["sv", "Svenska"], ["da", "Dansk"], ["nb", "Norsk"], ["fi", "Suomi"],
  ["pl", "Polski"], ["cs", "Čeština"], ["ro", "Română"], ["el", "Ελληνικά"],
  ["tr", "Türkçe"], ["ru", "Русский"], ["uk", "Українська"], ["ar", "العربية"],
  ["hi", "हिन्दी"], ["id", "Indonesia"], ["ja", "日本語"], ["ko", "한국어"],
  ["zh-Hans", "简体中文"], ["zh-Hant", "繁體中文"], ["th", "ไทย"], ["vi", "Tiếng Việt"]
];

function supportDetectInitialLanguage() {
  try {
    const fromApp = new URLSearchParams(location.search).get("lang");
    if (fromApp && SUPPORT_I18N[fromApp]) return fromApp;
  } catch (e) {}
  try {
    const saved = localStorage.getItem("supportLang");
    if (saved && SUPPORT_I18N[saved]) return saved;
  } catch (e) {}
  const nav = (navigator.language || "en").toLowerCase();
  if (SUPPORT_I18N[nav]) return nav;
  const short = nav.split("-")[0];
  if (short === "zh") return (nav.includes("tw") || nav.includes("hk") || nav.includes("hant")) ? "zh-Hant" : "zh-Hans";
  if (short === "nb" || short === "no") return "nb";
  if (short === "pt") return "pt-BR";
  for (const code of Object.keys(SUPPORT_I18N)) {
    if (code.split("-")[0].toLowerCase() === short) return code;
  }
  return "en";
}

function supportApplyLanguage(lang) {
  const dict = SUPPORT_I18N[lang] || SUPPORT_I18N.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach(function (el) {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) el.textContent = dict[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach(function (el) {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key] !== undefined) el.placeholder = dict[key];
  });

  const topicSelect = document.getElementById("topic");
  if (topicSelect && dict.topicOptions) {
    const keepIndex = topicSelect.selectedIndex;
    topicSelect.innerHTML = "";
    dict.topicOptions.forEach(function (label) {
      const opt = document.createElement("option");
      opt.textContent = label;
      topicSelect.appendChild(opt);
    });
    topicSelect.selectedIndex = keepIndex >= 0 && keepIndex < topicSelect.options.length ? keepIndex : 0;
  }

  const langSelect = document.getElementById("lang-select");
  if (langSelect && langSelect.value !== lang) langSelect.value = lang;

  try { localStorage.setItem("supportLang", lang); } catch (e) {}
}

function supportInitLanguageSwitcher() {
  const langSelect = document.getElementById("lang-select");
  if (langSelect && !langSelect.options.length) {
    SUPPORT_LANGS.forEach(function (pair) {
      const opt = document.createElement("option");
      opt.value = pair[0];
      opt.textContent = pair[1];
      langSelect.appendChild(opt);
    });
    langSelect.addEventListener("change", function () {
      supportApplyLanguage(langSelect.value);
    });
  }
  supportApplyLanguage(supportDetectInitialLanguage());
}

document.addEventListener("DOMContentLoaded", supportInitLanguageSwitcher);
